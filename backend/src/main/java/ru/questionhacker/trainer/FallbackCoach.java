package ru.questionhacker.trainer;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import org.springframework.stereotype.Component;

@Component
public class FallbackCoach {

    public String answer(String userText) {
        var categories = detect(userText);
        var primary = categories.getFirst();
        var secondary = categories.size() > 1 ? categories.get(1) : "Упрощение";

        return """
                ## Разбор ситуации

                Вы описали задачу так: **%s**

                Сейчас полезно не спешить с готовым советом, а сменить саму рамку мышления. Я бы начал с пары **«%s + %s»**: первая техника создаёт разрыв привычного сценария, вторая помогает превратить найденное в проверяемое действие.

                ## Почему эти категории

                **%s** %s

                **%s** %s

                ## Вопросы-взломщики

                1. %s
                2. %s
                3. %s
                4. %s
                5. %s

                ## Слишком общий вопрос → рабочая версия

                **Слабо:** «Как нам сделать лучше?»

                **Точнее:** «Какой один элемент текущего подхода создаёт основную потерю ценности, и какой обратимый эксперимент за 48 часов покажет, что мы нашли именно его?»

                ## Микро-эксперимент на 24–48 часов

                Выберите один вопрос выше. За 10 минут выпишите не меньше семи ответов без оценки. Затем сгруппируйте их в 2–3 механизма, выберите идею с высоким влиянием и низкой необратимостью и задайте заранее один критерий успеха. Не улучшайте всё сразу: проверьте одно предположение.

                > Какое негласное правило в вашей ситуации вы до сих пор принимали за факт, хотя его никто не проверял?
                """.formatted(
                escape(userText), primary, secondary,
                primary, rationale(primary),
                secondary, rationale(secondary),
                question(primary, userText, 0),
                question(primary, userText, 1),
                question(secondary, userText, 0),
                question(secondary, userText, 1),
                "Что должно измениться в формулировке результата, чтобы команда спорила не о действиях, а о ценности для пользователя?");
    }

    private List<String> detect(String text) {
        String value = text.toLowerCase(Locale.ROOT);
        var result = new ArrayList<String>();
        if (contains(value, "риск", "провал", "ошиб", "увол", "отток")) result.add("Инверсия");
        if (contains(value, "масштаб", "рост", "быстр", "бюджет", "ресурс")) result.add("Гипербола");
        if (contains(value, "иде", "застр", "скуч", "новое")) result.add("Кросс-дисциплина");
        if (contains(value, "стратег", "будущ", "лет", "устаре")) result.add("Футуризм");
        if (contains(value, "правил", "нельзя", "всегда", "рынок", "конкурент")) result.add("Провокация");
        if (contains(value, "клиент", "пользоват", "проблем", "ценност", "конверси")) result.add("Рефрейминг");
        if (contains(value, "слож", "лишн", "процесс", "функц", "архитект")) result.add("Упрощение");
        if (result.isEmpty()) result.add("Рефрейминг");
        if (result.size() == 1) result.add(result.getFirst().equals("Упрощение") ? "Инверсия" : "Упрощение");
        return result.stream().distinct().limit(2).toList();
    }

    private boolean contains(String value, String... needles) {
        for (String needle : needles) if (value.contains(needle)) return true;
        return false;
    }

    private String rationale(String category) {
        return switch (category) {
            case "Инверсия" -> "высвечивает условия провала и скрытые риски; после списка важно перевести каждый пункт в профилактическое действие.";
            case "Гипербола" -> "ломает линейное улучшение: при 10× масштабе или 1% ресурсов приходится менять механику, а не полировать старую.";
            case "Кросс-дисциплина" -> "помогает импортировать принцип решения из другой системы, не копируя её внешнюю форму.";
            case "Футуризм" -> "создаёт образ результата в будущем и позволяет методом backcasting восстановить вехи до сегодняшнего дня.";
            case "Провокация" -> "атакует негласное правило, которое команда перестала замечать и обсуждать.";
            case "Рефрейминг" -> "переводит разговор от текущего продукта или симптома к реальному исходу пользователя.";
            default -> "отделяет обязательное ядро от исторических артефактов и снижает лишнюю сложность.";
        };
    }

    private String question(String category, String context, int variant) {
        return switch (category) {
            case "Инверсия" -> variant == 0
                    ? "Как гарантированно ухудшить эту ситуацию за ближайший месяц — и какие из этих действий уже происходят?"
                    : "Представьте, что инициатива провалилась. Какой ранний сигнал был заметен, но его проигнорировали?";
            case "Гипербола" -> variant == 0
                    ? "Что пришлось бы изменить в самой механике, если результат нужен в 10 раз больше без роста команды?"
                    : "Как получить 70% эффекта, располагая только 10% текущего бюджета и времени?";
            case "Кросс-дисциплина" -> variant == 0
                    ? "Какая система вне вашей отрасли решает похожую задачу надёжнее — и какой её принцип можно перенести?"
                    : "Как бы эту ситуацию организовали режиссёр прямого эфира, диспетчер аэропорта или игровой дизайнер?";
            case "Футуризм" -> variant == 0
                    ? "Представьте, что через три года проблема исчезла. Какие три решения предшествовали этому результату?"
                    : "Что в сегодняшнем подходе будет выглядеть архаично из перспективы 2030 года?";
            case "Провокация" -> variant == 0
                    ? "Какое правило здесь «даже не обсуждают», и что откроется, если на неделю считать его необязательным?"
                    : "Что произойдёт, если перестать делать самую привычную часть процесса совсем?";
            case "Рефрейминг" -> variant == 0
                    ? "Какую работу человек на самом деле пытается выполнить, когда сталкивается с этой ситуацией?"
                    : "Что здесь является симптомом, а какой измеримый результат скрывается за ним?";
            default -> variant == 0
                    ? "Если оставить только 10% текущего решения, без чего ценность действительно развалится?"
                    : "Что здесь является объективной необходимостью, а что лишь исторически сложившимся шагом?";
        };
    }

    private String escape(String value) {
        return value.replace("\n", " ").strip();
    }
}
