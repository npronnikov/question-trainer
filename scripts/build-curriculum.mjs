function validate(categories) {
  if (categories.length !== 7) throw new Error(`Expected 7 categories, received ${categories.length}`);
  if (scenarios.scenarios.length !== 98) throw new Error(`Expected 98 scenarios, received ${scenarios.scenarios.length}`);
  const sourceIds = new Set(canonical.sources.map(source => source.key));
  const categoryCodes = new Set(categories.map(category => category.code));
  for (const category of categories) {
    const example = category.workedExample;
    if (!example || example.reasoningSteps.length < 3 || example.reasoningSteps.length > 5) {
      throw new Error(`${category.code} requires 3-5 worked-example reasoning steps`);
    }
    if (category.questionTemplates.length !== 5 || category.cases.length !== 3) {
      throw new Error(`${category.code} has incomplete researched learning content`);
    }
    if (!category.quickExercise.trim() || !category.experiment.trim()) {
      throw new Error(`${category.code} lacks an exercise or experiment`);
    }
    if (!categoryCodes.has(example.confusion.otherCategory) || example.confusion.otherCategory === category.code) {
      throw new Error(`${category.code} has an invalid confusion category`);
    }
    for (const item of category.cases) {
      if (!item.sourceIds.length || item.sourceIds.some(id => !sourceIds.has(id))) {
        throw new Error(`${category.code} case ${item.slug} has unknown sources`);
      }
    }
  }
}

const categories = canonical.categories.map(category => {
  const researchId = category.code === 'BACKCASTING' ? 'FUTURISM' : category.code;
  const detail = researchById.get(researchId);
  if (!detail) throw new Error(`Missing research for ${category.code}`);
  return {
    ...category,
    workedExample: workedExamples[category.code],
    questionTemplates: detail.questionTemplates,
    quickExercise: detail.quickExercise,
    experiment: detail.experiment,
    cases: detail.cases
  };
});

validate(categories);
fs.writeFileSync(curriculumPath, `${JSON.stringify({ ...canonical, categories }, null, 2)}\n`);
console.log(`Generated ${categories.length} enriched categories, ${canonical.sources.length} sources and preserved ${scenarios.scenarios.length} scenarios.`);
